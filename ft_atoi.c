#include "libft.h"

int	ft_atoi(char const *nptr)
{
	int	i;
	int	sign;
	int	result;

	i = 0;
	sign = 1;
	result = 0;
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == 32)
		i++;
	if (nptr[i] == '-')
	{
		sign = -1;
		i++;
	}
	else if (nptr[i] == '+')
		i++;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		if (result < 0 && sign < 0)
			return (0);
		else if (result < 0 && sign > 0)
			return (-1);
		result = result * 10 + nptr[i++] - '0';
	}
	return (result * sign);
}
